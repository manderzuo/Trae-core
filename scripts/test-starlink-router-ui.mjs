import assert from 'node:assert/strict';
import fs from 'node:fs';

const html = fs.readFileSync(new URL('../starlink-dimension-router/static/index.html', import.meta.url), 'utf8');
assert.match(html, /setInterval\(/, 'management page must auto-refresh after connection');
assert.match(html, /admin\/v1\/login/, 'management page must expose account login');
assert.match(html, /admin\/v1\/session/, 'management page must restore the current session');
assert.match(html, /admin\/v1\/logout/, 'management page must expose logout');
assert.match(html, /修改管理员密码/, 'management page must expose password change');
assert.match(html, /credentials:'same-origin'/, 'management page must use same-origin cookies');
assert.doesNotMatch(html, /localStorage/, 'management page must not persist admin credentials in localStorage');
assert.doesNotMatch(html, /ADMIN_KEY_STORAGE/, 'management page must not contain the old admin key storage constant');
assert.match(html, /max_concurrency/, 'management page must submit a per-key concurrency limit');
assert.match(html, /display_name/, 'key creation must accept a display name without a manual user id');
assert.match(html, /data-action="copy"/, 'management page must expose per-key copy');
assert.match(html, /使用情况/, 'management page must expose key usage details');
assert.match(html, /data-action="delete"/, 'each ordinary key must expose a delete action');
assert.match(html, /quota\?resource_kind=credits/, 'delete confirmation must fetch the latest key balance');
assert.match(html, /method:'DELETE'/, 'confirmed deletion must use the protected delete endpoint');
assert.match(html, /window\.confirm\(/, 'deletion must require a browser confirmation');
assert.match(html, /if \(!confirmed\) return;[\s\S]*?method:'DELETE'/, 'cancelling confirmation must not send the delete request');
assert.match(html, /已实扣（不返还）/, 'confirmation must explain that spent credits are not refundable');
assert.match(html, /returned_credits/, 'success feedback must show the actual refunded amount');
assert.doesNotMatch(html, /id="userId"/, 'management page must remove manual user id creation');
assert.doesNotMatch(html, /活跃账号/, 'overview must not show active upstream account count');
assert.match(html, /文字处理/, 'scope labels must be translated to Chinese');
assert.match(html, /视频生成/, 'video scope label must be translated to Chinese');
assert.match(html, /素材上传/, 'asset upload scope must be translated to Chinese');
assert.match(html, /积分实扣趋势/, 'management page must show the consumption trend');
assert.match(html, /usage-trend/, 'management page must request the points consumption trend');
assert.match(html, /最近 24 小时/, 'trend chart must support a 24 hour range');
assert.match(html, /id="page-overview"/, 'dashboard must have a dedicated overview page');
assert.match(html, /id="page-keys"/, 'dashboard must have a dedicated key-management page');
assert.match(html, /id="page-settings"/, 'configuration must have a dedicated settings page');
assert.ok(html.indexOf('id="page-settings"') < html.indexOf('AI Work 桥接配置'), 'bridge configuration must live under settings');
assert.match(html, /AI Work 当前总积分/, 'overview must show the current upstream total');
assert.match(html, /统一积分/, 'overview must use one unified credit balance');
assert.match(html, /剩余可分配/, 'key management must show upstream allocatable credits');
assert.match(html, /分配积分/, 'key management must allow direct allocation');
assert.doesNotMatch(html, /充值到积分池|quota\/pool/, 'the unified-credit UI must not expose legacy pool top-up');
console.log('starlink router UI contract: PASS');
